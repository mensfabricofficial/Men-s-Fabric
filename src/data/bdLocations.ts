export const normalizeDivisionName = (raw?: string): string => {
  if (!raw) return 'Dhaka';
  const trimmed = raw.trim();
  const lower = trimmed.toLowerCase();
  if (lower === 'chittagong') return 'Chattogram';
  if (lower === 'barisal') return 'Barishal';
  const matched = BD_DIVISIONS.find((d) => d.toLowerCase() === lower);
  return matched || 'Dhaka';
};

export const normalizeDistrictName = (raw?: string): string => {
  if (!raw) return 'Dhaka';
  const trimmed = raw.trim();
  const lower = trimmed.toLowerCase();
  if (DISTRICT_ALIASES[lower]) return DISTRICT_ALIASES[lower];
  const exactKey = Object.keys(BD_THANAS_BY_DISTRICT).find(
    (k) => k.toLowerCase() === lower
  );
  return exactKey || trimmed;
};

export const getDistrictsForDivision = (division?: string): string[] => {
  const normDiv = normalizeDivisionName(division);
  return BD_DISTRICTS_BY_DIVISION[normDiv] || BD_DISTRICTS_BY_DIVISION.Dhaka;
};

export const getThanasForDistrict = (district?: string, division?: string): string[] => {
  const normalized = normalizeDistrictName(district);
  if (BD_THANAS_BY_DISTRICT[normalized]) {
    return BD_THANAS_BY_DISTRICT[normalized];
  }
  const divDistricts = getDistrictsForDivision(division);
  const fallbackDist = divDistricts[0];
  return BD_THANAS_BY_DISTRICT[fallbackDist] || [];
};
